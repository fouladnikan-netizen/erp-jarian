/** Bundled seed / mock-offline fallback. Live catalog is PostgreSQL (DDL-48). */
export function lexiconSeedEntries() {
  return [
    ...RAW_PHRASES.map(([faDisplay, latin]) => ({ faDisplay, latin, kind: 'phrase' })),
    ...RAW_ATTRIBUTE_CODES.map(([faDisplay, latin]) => ({ faDisplay, latin, kind: 'attribute_code' })),
    ...RAW_UOM_CODES.map(([faDisplay, latin]) => ({ faDisplay, latin, kind: 'uom_code' })),
  ];
}

export function catalogsFromEntries(entries) {
  const phrases = [];
  const attributeCodes = {};
  const uomCodes = {};
  for (const row of entries || []) {
    const fa = normalizeFaKey(row.faNormalized || row.fa || row.faDisplay);
    const latin = String(row.latin || '').trim();
    if (!fa || !latin || row.isActive === false) continue;
    if (row.kind === 'attribute_code') attributeCodes[fa] = latin;
    else if (row.kind === 'uom_code') uomCodes[fa] = latin;
    else phrases.push({ fa, latin });
  }
  phrases.sort((a, b) => b.fa.length - a.fa.length || a.fa.localeCompare(b.fa, 'fa'));
  return { phrases, attributeCodes, uomCodes };
}

