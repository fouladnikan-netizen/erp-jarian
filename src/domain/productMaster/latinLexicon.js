export function normalizeFaKey(value) {
  return String(value || '')
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/[\u200c\u200d]/g, '')
    .replace(/[‌ـ]/g, '')
    .replace(/[()[\]{}«»"'،,._+/\\-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

